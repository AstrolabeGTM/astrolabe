package mcp

import (
	"context"
	"fmt"
	"io"
	"sort"
	"strings"

	sdk "github.com/modelcontextprotocol/go-sdk/mcp"
)

// ToolInfo is one tool for the reference listing.
type ToolInfo struct {
	Name        string
	Summary     string // first sentence of the description
	SandboxOnly bool
}

// ListTools returns every tool the server can offer, sorted by name,
// including the ones only registered in sandbox mode. It needs no database.
func ListTools(ctx context.Context) ([]ToolInfo, error) {
	live, err := toolDescriptions(ctx, "live")
	if err != nil {
		return nil, err
	}
	sandbox, err := toolDescriptions(ctx, "sandbox")
	if err != nil {
		return nil, err
	}
	var out []ToolInfo
	for name, desc := range sandbox {
		_, inLive := live[name]
		out = append(out, ToolInfo{Name: name, Summary: summary(desc), SandboxOnly: !inLive})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

func toolDescriptions(ctx context.Context, mode string) (map[string]string, error) {
	s := &Server{Mode: mode}
	st, ct := sdk.NewInMemoryTransports()
	ss, err := s.Build("docs").Connect(ctx, st, nil)
	if err != nil {
		return nil, err
	}
	defer ss.Close()
	cs, err := sdk.NewClient(&sdk.Implementation{Name: "docs", Version: "0"}, nil).Connect(ctx, ct, nil)
	if err != nil {
		return nil, err
	}
	defer cs.Close()
	res, err := cs.ListTools(ctx, nil)
	if err != nil {
		return nil, err
	}
	m := map[string]string{}
	for _, t := range res.Tools {
		m[t.Name] = t.Description
	}
	return m, nil
}

// summary is the description up to its first sentence end.
func summary(desc string) string {
	if i := strings.Index(desc, " (Sales terms:"); i >= 0 {
		desc = desc[:i]
	}
	for i := 0; i+2 < len(desc); i++ {
		if desc[i] == '.' && desc[i+1] == ' ' && desc[i+2] >= 'A' && desc[i+2] <= 'Z' {
			return desc[:i+1]
		}
	}
	return desc
}

// WriteTools prints the tool list: plain text, or a Markdown table.
func WriteTools(w io.Writer, tools []ToolInfo, markdown bool) {
	if markdown {
		fmt.Fprint(w, "# Astrolabe MCP tools\n\n")
		fmt.Fprint(w, "<!-- Generated by `astrolabe mcp tools -md`. Do not edit; a test fails when this file is stale. -->\n\n")
		fmt.Fprintf(w, "%d tools, the same over stdio (`astrolabe mcp`) and HTTP (`/mcp`). Each description also lists its sales-term equivalents.\n\n", len(tools))
		fmt.Fprint(w, "| Tool | What it does |\n| --- | --- |\n")
		for _, t := range tools {
			s := strings.ReplaceAll(t.Summary, "|", `\|`)
			if t.SandboxOnly {
				s += " *(sandbox mode only)*"
			}
			fmt.Fprintf(w, "| `%s` | %s |\n", t.Name, s)
		}
		return
	}
	width := 0
	for _, t := range tools {
		width = max(width, len(t.Name))
	}
	for _, t := range tools {
		s := t.Summary
		if t.SandboxOnly {
			s += " (sandbox mode only)"
		}
		fmt.Fprintf(w, "%-*s  %s\n", width, t.Name, s)
	}
}
